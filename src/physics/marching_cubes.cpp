constexpr uint32_t GRANULARITY = 64;

void forRange(core::JobSystem* jobs, uint32_t count, const std::function<void(uint32_t, uint32_t)>& body) {
    if (jobs != nullptr && count > GRANULARITY) {
        jobs->parallelFor(count, GRANULARITY, body);
    } else if (count > 0) {
        body(0, count);
    }
}

// 표본점 하나에 이웃 입자를 모은다. shaders/fluid_field.comp 의 같은 식이다. 커널은 poly6 의 모양만
// 빌린 무차원 값이라 등치값도 무차원이다.
float sampleField(const glm::vec4* particles, uint32_t count, glm::vec3 point, float radius) {
    float radiusSq = radius * radius;
    float total = 0.0F;
    for (uint32_t i = 0; i < count; ++i) {
        glm::vec3 delta = glm::vec3{particles[i]} - point;
        float distanceSq = glm::dot(delta, delta);
        if (distanceSq >= radiusSq) {
            continue;
        }
        float d = 1.0F - distanceSq / radiusSq;
        total += d * d * d;
    }
    return total;
}

// 장에서 값 하나를 읽는다. 격자 밖은 0 이라 표면이 격자 경계에서 닫힌다.
float fieldAt(const std::vector<float>& field, uint32_t samples, glm::ivec3 coordinate) {
    if (coordinate.x < 0 || coordinate.y < 0 || coordinate.z < 0 || coordinate.x >= static_cast<int>(samples) ||
        coordinate.y >= static_cast<int>(samples) || coordinate.z >= static_cast<int>(samples)) {
        return 0.0F;
    }
    size_t index = static_cast<size_t>(coordinate.z) * samples * samples + static_cast<size_t>(coordinate.y) * samples +
                   static_cast<size_t>(coordinate.x);
    return field[index];
}

