void buildFluidField(const std::vector<glm::vec4>& particles,
                     const FluidParams& params,
                     uint32_t resolution,
                     std::vector<float>& field,
                     core::JobSystem* jobs) {
    uint32_t samples = resolution + 1;
    field.assign(static_cast<size_t>(samples) * samples * samples, 0.0F);
    if (particles.empty()) {
        return;
    }
    glm::vec3 origin = params.containerMin;
    glm::vec3 span = params.containerMax - params.containerMin;
    glm::vec3 cell = span / static_cast<float>(resolution);
    float radius = params.smoothingRadius;
    const glm::vec4* data = particles.data();
    auto count = static_cast<uint32_t>(particles.size());

    // ponytail: 표본마다 입자 전부를 훑는다. 격자 48³ · 입자 8192 면 워커에 나눠도 무겁다. GPU 경로는
    // 이미 만들어 둔 해시 격자를 쓰므로 그런 문제가 없다. CPU 백엔드에서 표면을 켜면 격자 해상도를
    // 낮춰 쓴다.
    forRange(jobs, samples * samples * samples, [&](uint32_t begin, uint32_t end) {
        for (uint32_t i = begin; i < end; ++i) {
            uint32_t x = i % samples;
            uint32_t y = (i / samples) % samples;
            uint32_t z = i / (samples * samples);
            // 격자 가장자리는 0 이다. shaders/fluid_field.comp 와 같은 규칙이라 두 백엔드가 같은 자리에서
            // 표면을 닫는다.
            if (x == 0 || y == 0 || z == 0 || x == resolution || y == resolution || z == resolution) {
                continue;
            }
            glm::vec3 point = origin + glm::vec3{x, y, z} * cell;
            field[i] = sampleField(data, count, point, radius);
        }
    });
}

uint32_t marchFluidField(const std::vector<float>& field,
                         uint32_t resolution,
                         glm::vec3 origin,
                         glm::vec3 cellSize,
                         float iso,
                         SurfaceVertex* out,
                         uint32_t capacity,
                         core::JobSystem* jobs) {
    uint32_t samples = resolution + 1;
    if (field.size() != static_cast<size_t>(samples) * samples * samples || capacity < 3) {
        return 0;
    }
    std::atomic<uint32_t> written{0};
    // 처음 넘친 자리. 그 아래는 모두 실제로 쓰인 칸이다. shaders/fluid_marching.comp 와 같은 규칙이다.
    std::atomic<uint32_t> limit{capacity};

    forRange(jobs, resolution * resolution * resolution, [&](uint32_t begin, uint32_t end) {
        for (uint32_t i = begin; i < end; ++i) {
            glm::ivec3 base{i % resolution, (i / resolution) % resolution, i / (resolution * resolution)};
            std::array<float, 8> values{};
            uint32_t code = 0;
            for (uint32_t corner = 0; corner < 8; ++corner) {
                values[corner] = fieldAt(field, samples, base + MC_CORNERS[corner]);
                if (values[corner] >= iso) {
                    code |= 1U << corner;
                }
            }
            const std::array<int8_t, MC_TABLE_WIDTH>& entry = MC_TABLE[code];
            if (entry[0] < 0) {
                continue;
            }

            // 모서리마다 위치와 법선을 한 번만 낸다. 법선은 표본 사이의 기울기를 선형 보간한 것이다.
            std::array<glm::vec3, 12> points{};
            std::array<glm::vec3, 12> normals{};
            std::array<bool, 12> ready{};
            auto edgePoint = [&](uint32_t edge) {
                if (ready[edge]) {
                    return;
                }
                ready[edge] = true;
                uint8_t a = MC_EDGES[edge][0];
                uint8_t b = MC_EDGES[edge][1];
                float va = values[a];
                float vb = values[b];
                float t = std::abs(vb - va) > 1.0e-8F ? (iso - va) / (vb - va) : 0.5F;
                t = std::clamp(t, 0.0F, 1.0F);
                glm::ivec3 ca = base + MC_CORNERS[a];
                glm::ivec3 cb = base + MC_CORNERS[b];
                glm::vec3 pa = origin + glm::vec3{ca} * cellSize;
                glm::vec3 pb = origin + glm::vec3{cb} * cellSize;
                points[edge] = pa + (pb - pa) * t;
                // 중앙 차분. 칸 크기로 나누지 않으면 용기가 정육면체가 아닐 때 법선이 기운다.
                auto gradient = [&](glm::ivec3 c) {
                    return glm::vec3{fieldAt(field, samples, c + glm::ivec3{1, 0, 0}) -
                                         fieldAt(field, samples, c - glm::ivec3{1, 0, 0}),
                                     fieldAt(field, samples, c + glm::ivec3{0, 1, 0}) -
                                         fieldAt(field, samples, c - glm::ivec3{0, 1, 0}),
                                     fieldAt(field, samples, c + glm::ivec3{0, 0, 1}) -
                                         fieldAt(field, samples, c - glm::ivec3{0, 0, 1})} /
                           cellSize;
                };
                // 값이 커지는 쪽이 유체 안이므로 바깥 법선은 기울기의 반대다.
                normals[edge] = -(gradient(ca) + (gradient(cb) - gradient(ca)) * t);
            };

            uint32_t vertices = 0;
            while (vertices < MC_TABLE_WIDTH && entry[vertices] >= 0) {
                ++vertices;
            }
            uint32_t slot = written.fetch_add(vertices, std::memory_order_relaxed);
            if (slot + vertices > capacity) {
                uint32_t seen = limit.load(std::memory_order_relaxed);
                while (seen > slot && !limit.compare_exchange_weak(seen, slot, std::memory_order_relaxed)) {
                }
                continue;
            }
            for (uint32_t v = 0; v < vertices; ++v) {
                auto edge = static_cast<uint32_t>(entry[v]);
                edgePoint(edge);
                out[slot + v].position = points[edge];
                out[slot + v].normal = asset::packUnitVector(glm::normalize(
                    glm::length(normals[edge]) > 1.0e-12F ? normals[edge] : glm::vec3{0.0F, 1.0F, 0.0F}));
            }
        }
    });

    return std::min(written.load(std::memory_order_relaxed), limit.load(std::memory_order_relaxed));
}

